local H = require("helpers")
local summary = require("fugitive.buffers.summary")
local discard = require("fugitive.discard")

local function open(repo)
  vim.cmd("cd " .. vim.fn.fnameescape(repo.root))
  vim.cmd("Git")
  local buf = vim.api.nvim_get_current_buf()
  H.wait(function()
    return summary.state(buf) and summary.state(buf).tick > 0
  end)
  return buf
end

local function after(buf, fn)
  local st = summary.state(buf)
  local tick = st.tick
  fn()
  H.wait(function()
    return st.tick > tick and not st.running
  end, "refresh")
end

local function goto_line(pattern)
  local l = assert(H.find_line(pattern), "no line " .. pattern)
  vim.api.nvim_win_set_cursor(0, { l, 0 })
end

local function restore_latest(repo, buf)
  after(buf, function()
    discard.restore_latest(require("fugitive.git.repo").find(repo.root))
  end)
end

describe("discard (X) and recovery", function()
  local log, restore
  before_each(function()
    H.reset_ui()
    log, restore = H.capture_notify()
  end)
  after_each(function()
    restore()
  end)

  it("untracked file: deleted, then restored", function()
    local repo = H.repo({ files = { ["a"] = "a\n" } })
    repo:write("u.txt", "precious\n")
    local buf = open(repo)
    goto_line("^%? u.txt")
    after(buf, function()
      H.feed("X")
    end)
    assert.is_nil(repo:read("u.txt"))
    local journal = discard.read_journal(require("fugitive.git.repo").find(repo.root))
    assert.equals(1, #journal)
    assert.equals("untracked", journal[1].kind)
    assert.truthy(vim.iter(log):any(function(m)
      return m.msg:match(":Git restore%-discard")
        and m.msg:match(journal[1].worktree_blob:sub(1, 7))
    end))
    assert.truthy(H.find_line("^Discarded: u.txt"))
    restore_latest(repo, buf)
    assert.equals("precious\n", repo:read("u.txt"))
    assert.equals(0, #discard.read_journal(require("fugitive.git.repo").find(repo.root)))
  end)

  it("unstaged modification: checked out, then restored via :Git restore-discard", function()
    local repo = H.repo({ files = { ["f"] = "orig\n" } })
    repo:write("f", "edited\n")
    local buf = open(repo)
    goto_line("^M f")
    after(buf, function()
      H.feed("X")
    end)
    assert.equals("orig\n", repo:read("f"))
    after(buf, function()
      vim.cmd("Git restore-discard")
    end)
    assert.equals("edited\n", repo:read("f"))
    assert.equals(" M f\n", repo:status())
  end)

  it("staged-only change: index entry restored", function()
    local repo = H.repo({ files = { ["f"] = "orig\n" } })
    repo:write("f", "staged\n")
    repo:git("add", "f")
    local buf = open(repo)
    local sl = H.find_line("^Staged")
    vim.api.nvim_win_set_cursor(0, { sl + 1, 0 })
    after(buf, function()
      H.feed("X")
    end)
    assert.equals("", repo:status())
    assert.equals("orig\n", repo:read("f"))
    restore_latest(repo, buf)
    assert.equals("M  f\n", repo:status())
    assert.equals("staged\n", repo:git("show", ":f"))
    assert.equals("staged\n", repo:read("f"))
  end)

  it("partial-hunk discard: whole file saved and restorable", function()
    local lines = {}
    for i = 1, 20 do
      lines[i] = "l" .. i
    end
    local repo = H.repo({ files = { ["f"] = table.concat(lines, "\n") .. "\n" } })
    lines[2] = "X2"
    lines[19] = "X19"
    local edited = table.concat(lines, "\n") .. "\n"
    repo:write("f", edited)
    local buf = open(repo)
    goto_line("^M f")
    after(buf, function()
      H.feed(">")
    end)
    goto_line("^%+X19")
    after(buf, function()
      H.feed("X")
    end)
    local now = repo:read("f")
    assert.truthy(now:match("X2\n"))
    assert.falsy(now:match("X19"))
    local journal = discard.read_journal(require("fugitive.git.repo").find(repo.root))
    assert.equals("partial", journal[#journal].kind)
    restore_latest(repo, buf)
    assert.equals(edited, repo:read("f"))
  end)

  it("tracked symlink: restored as a link", function()
    local repo = H.repo({ files = { ["target"] = "t\n" } })
    vim.uv.fs_symlink("target", repo:path("link"))
    repo:commit("link")
    os.remove(repo:path("link"))
    vim.uv.fs_symlink("elsewhere", repo:path("link"))
    local buf = open(repo)
    goto_line("^M link")
    after(buf, function()
      H.feed("X")
    end)
    assert.equals("target", vim.uv.fs_readlink(repo:path("link")))
    local journal = discard.read_journal(require("fugitive.git.repo").find(repo.root))
    assert.equals("120000", journal[#journal].mode)
    restore_latest(repo, buf)
    assert.equals("link", vim.uv.fs_lstat(repo:path("link")).type)
    assert.equals("elsewhere", vim.uv.fs_readlink(repo:path("link")))
  end)

  it("discarding a work-tree deletion is undone by deleting again", function()
    local repo = H.repo({ files = { ["f"] = "f\n" } })
    os.remove(repo:path("f"))
    local buf = open(repo)
    goto_line("^D f")
    after(buf, function()
      H.feed("X")
    end)
    assert.equals("f\n", repo:read("f"))
    restore_latest(repo, buf)
    assert.is_nil(repo:read("f"))
    assert.equals(" D f\n", repo:status())
  end)

  it("refuses everything when hash-object fails (read-only object dir)", function()
    if vim.uv.getuid and vim.uv.getuid() == 0 then
      pending("running as root: permissions are not enforced")
      return
    end
    local repo = H.repo({ files = { ["f"] = "orig\n" } })
    repo:write("f", "edited\n")
    repo:write("u", "untracked\n")
    local buf = open(repo)
    local objects = repo.root .. "/.git/objects"
    local function chmod_tree(mode)
      vim.uv.fs_chmod(objects, tonumber(mode, 8))
      for name, t in vim.fs.dir(objects) do
        if t == "directory" then
          vim.uv.fs_chmod(objects .. "/" .. name, tonumber(mode, 8))
        end
      end
    end
    chmod_tree("555")
    local ok, err = pcall(function()
      vim.cmd("normal! gg")
      local first = assert(H.find_line("^%? u"))
      local last = assert(H.find_line("^M f"))
      vim.api.nvim_win_set_cursor(0, { first, 0 })
      H.feed("V" .. (last - first) .. "jX")
      vim.wait(300)
    end)
    chmod_tree("755")
    assert(ok, err)
    assert.equals("edited\n", repo:read("f"))
    assert.equals("untracked\n", repo:read("u"))
    assert.truthy(vim.iter(log):any(function(m)
      return m.msg:match("discard refused") and m.level == vim.log.levels.ERROR
    end))
    assert.equals(0, #discard.read_journal(require("fugitive.git.repo").find(repo.root)))
  end)

  it("refuses directories and submodules", function()
    local repo = H.repo({ files = { ["a"] = "a\n" } })
    repo:write("dir/x", "x\n")
    repo:write("dir/y", "y\n")
    local buf = open(repo)
    goto_line("^%? dir/$")
    H.feed("X")
    vim.wait(100)
    assert.equals("x\n", repo:read("dir/x"))
    assert.truthy(vim.iter(log):any(function(m)
      return m.msg:match("will not delete directory")
    end))
    local _ = buf
  end)

  it("2X/3X take ours/theirs for an unmerged file", function()
    local repo = H.repo({ files = { ["c"] = "base\n" } })
    repo:git("checkout", "-q", "-b", "topic")
    repo:commit("topic", { ["c"] = "topic\n" })
    repo:git("checkout", "-q", "main")
    repo:commit("main", { ["c"] = "main\n" })
    repo:git("merge", "topic", { allow_fail = true })
    local buf = open(repo)
    goto_line("^U c")
    after(buf, function()
      H.feed("3X")
    end)
    assert.equals("topic\n", repo:read("c"))
    goto_line("^U c")
    after(buf, function()
      H.feed("2X")
    end)
    assert.equals("main\n", repo:read("c"))
  end)

  it(":FugitiveRestore picks from the journal", function()
    local repo = H.repo({ files = { ["a"] = "a\n", ["b"] = "b\n" } })
    repo:write("a", "A\n")
    repo:write("b", "B\n")
    local buf = open(repo)
    goto_line("^M a")
    after(buf, function()
      H.feed("X")
    end)
    goto_line("^M b")
    after(buf, function()
      H.feed("X")
    end)
    local orig = vim.ui.select
    local offered
    vim.ui.select = function(items, opts, cb)
      offered = vim.tbl_map(function(i)
        return opts.format_item(i)
      end, items)
      cb(items[#items]) -- the oldest: a
    end
    after(buf, function()
      vim.cmd("FugitiveRestore")
    end)
    vim.ui.select = orig
    assert.equals(2, #offered)
    assert.truthy(offered[1]:match(" b "))
    assert.equals("A\n", repo:read("a"))
    assert.equals("b\n", repo:read("b"))
  end)
end)
