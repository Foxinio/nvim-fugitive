local H = require("helpers")
local object = require("nvim-fugitive.object")

local function url(repo, commit, path)
  return object.format(repo.root .. "/.git", commit, path)
end

describe("object syntax", function()
  local repo, r
  before_each(function()
    H.reset_ui()
    repo = H.repo({ files = { ["dir/f.txt"] = "1\n", ["Makefile"] = "all:\n" } })
    repo:commit("second", { ["dir/f.txt"] = "2\n" })
    repo:commit("fix the frobnicator", { ["dir/f.txt"] = "3\n" })
    vim.cmd("cd " .. repo.root)
    r = require("nvim-fugitive.git.repo").find(repo.root)
  end)

  local function find(spec)
    return object.find(r, object.expand(spec, r))
  end

  it("resolves revisions, paths, stages and trees", function()
    assert.equals(url(repo, repo:rev("HEAD")), find("@"))
    assert.equals(url(repo, repo:rev("HEAD~1")), find("HEAD^"))
    assert.equals(url(repo, repo:rev("HEAD~1"), "dir/f.txt"), find("@^:dir/f.txt"))
    assert.equals(url(repo, repo:rev("HEAD"), ""), find("main:"))
    assert.equals(url(repo, "0", "Makefile"), find(":Makefile"))
    assert.equals(url(repo, "2", "dir/f.txt"), find(":2:dir/f.txt"))
    assert.equals(url(repo, repo:rev("HEAD^{tree}")), find("HEAD^{tree}"))
  end)

  it("treats bare words that are not revisions as work-tree files", function()
    assert.equals(repo:path("Makefile"), find("Makefile"))
    assert.equals(repo:path("dir/f.txt"), find(":(top)dir/f.txt"))
    assert.equals(repo:path("dir/f.txt"), find("./dir/f.txt"))
    assert.equals(repo.root .. "/.git/config", find(".git/config"))
    assert.equals(url(repo, ""), find(":"))
  end)

  it("finds commits by message with :/ and merge bases with ...", function()
    assert.equals(url(repo, repo:rev("HEAD")), find(":/frobnicator"))
    repo:git("branch", "side", "HEAD~1")
    assert.equals(url(repo, repo:rev("HEAD~1")), find("main...side"))
  end)

  it("expands %, :% and ! relative to the current buffer", function()
    vim.cmd("edit " .. repo:path("dir/f.txt"))
    assert.equals(url(repo, "0", "dir/f.txt"), find(":%"))
    assert.equals(url(repo, repo:rev("HEAD~2"), "dir/f.txt"), find("@~2:%"))
    assert.equals(repo:path("dir/f.txt"), find("%"))
    -- ! in a blob at a commit is that commit
    vim.cmd("edit " .. vim.fn.fnameescape(url(repo, repo:rev("HEAD~1"), "dir/f.txt")))
    assert.equals(url(repo, repo:rev("HEAD~1")), find("!"))
    assert.equals(url(repo, repo:rev("HEAD~1"), "Makefile"), find("!:Makefile"))
    assert.equals(url(repo, repo:rev("HEAD~2")), find("!^"))
  end)
end)

describe(":Gedit family", function()
  local repo
  before_each(function()
    H.reset_ui()
    repo = H.repo({ files = { ["a.txt"] = "committed\n" } })
    repo:write("a.txt", "staged\n")
    repo:git("add", "a.txt")
    repo:write("a.txt", "worktree\n")
    vim.cmd("cd " .. repo.root)
  end)

  it(":Gedit with no argument toggles between work tree and index", function()
    vim.cmd("edit a.txt")
    vim.cmd("Gedit")
    assert.equals(url(repo, "0", "a.txt"), vim.api.nvim_buf_get_name(0))
    assert.same({ "staged" }, H.lines(0))
    vim.cmd("Gedit")
    assert.equals(repo:path("a.txt"), vim.api.nvim_buf_get_name(0))
  end)

  it(":Gsplit, :Gvsplit, :Gtabedit and :Gpedit open windows", function()
    vim.cmd("edit a.txt")
    vim.cmd("Gsplit HEAD:a.txt")
    assert.equals(2, #vim.api.nvim_tabpage_list_wins(0))
    assert.same({ "committed" }, H.lines(0))
    vim.cmd("Gvsplit :a.txt")
    assert.equals(3, #vim.api.nvim_tabpage_list_wins(0))
    vim.cmd("Gtabedit @")
    assert.equals(2, #vim.api.nvim_list_tabpages())
    assert.equals("commit", vim.b.fugitive_type)
    vim.cmd("tabclose")
    vim.cmd("Gpedit HEAD:a.txt")
    local previews = vim.tbl_filter(function(w)
      return vim.wo[w].previewwindow
    end, vim.api.nvim_tabpage_list_wins(0))
    assert.equals(1, #previews)
  end)

  it(":Gedit : opens the summary and :Gedit - the last :Git output", function()
    vim.cmd("Gedit :")
    assert.equals("fugitive", vim.bo.filetype)
    local log, restore = H.capture_notify()
    local before = require("nvim-fugitive.ui.output").get(1)
    vim.cmd("Git --no-pager log --oneline")
    H.wait(function()
      local e = require("nvim-fugitive.ui.output").get(1)
      return e ~= before and not e.running
    end)
    restore()
    vim.cmd("Gedit -")
    assert.truthy(H.find_line("initial"))
    local _ = log
  end)

  it("errors on unknown objects", function()
    local log, restore = H.capture_notify()
    vim.cmd("Gedit :/no-such-message")
    restore()
    assert.equals(vim.log.levels.ERROR, log[1].level)
  end)
end)

describe("object buffer navigation", function()
  before_each(function()
    H.reset_ui()
  end)

  it("~ P C - walk ancestors, parents, the commit and up the tree", function()
    local repo = H.repo({ files = { ["d/f"] = "1\n" } })
    repo:commit("two", { ["d/f"] = "2\n" })
    repo:commit("three", { ["d/f"] = "3\n" })
    local head = repo:rev("HEAD")
    vim.cmd("edit " .. vim.fn.fnameescape(url(repo, head, "d/f")))
    H.feed("~")
    assert.equals(url(repo, repo:rev("HEAD~1"), "d/f"), vim.api.nvim_buf_get_name(0))
    H.feed("1P")
    assert.same({ "1" }, H.lines(0))
    -- - goes to the containing tree with the cursor on the entry, then up
    vim.cmd("edit " .. vim.fn.fnameescape(url(repo, head, "d/f")))
    H.feed("-")
    assert.equals(url(repo, head, "d/"), vim.api.nvim_buf_get_name(0))
    assert.equals("f", vim.api.nvim_get_current_line())
    H.feed("-")
    assert.equals(url(repo, head, ""), vim.api.nvim_buf_get_name(0))
    H.feed("-")
    assert.equals(url(repo, head), vim.api.nvim_buf_get_name(0))
    vim.cmd("edit " .. vim.fn.fnameescape(url(repo, head, "d/f")))
    H.feed("C")
    assert.equals(url(repo, head), vim.api.nvim_buf_get_name(0))
  end)
end)
