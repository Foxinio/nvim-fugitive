local H = require("helpers")
local object = require("nvim-fugitive.object")

describe("fugitive:// reader", function()
  before_each(function()
    H.reset_ui()
  end)

  it("reads blobs at a commit and in the index, with filetype detection", function()
    local repo = H.repo({ files = { ["src/x.sh"] = "echo 1\n" } })
    local head = repo:rev("HEAD")
    repo:write("src/x.sh", "echo 2\n")
    repo:git("add", ".")
    vim.cmd("edit " .. vim.fn.fnameescape(object.format(repo.root .. "/.git", head, "src/x.sh")))
    assert.same({ "echo 1" }, H.lines(0))
    assert.equals("sh", vim.bo.filetype)
    assert.is_false(vim.bo.modifiable)
    assert.equals("nowrite", vim.bo.buftype)
    vim.cmd("edit " .. vim.fn.fnameescape(object.format(repo.root .. "/.git", "0", "src/x.sh")))
    assert.same({ "echo 2" }, H.lines(0))
  end)

  it("reads trees and opens entries with <CR>", function()
    local repo = H.repo({ files = { ["dir/a"] = "a\n", ["top"] = "t\n" } })
    local head = repo:rev("HEAD")
    vim.cmd("edit " .. vim.fn.fnameescape(object.format(repo.root .. "/.git", head, "")))
    assert.equals("tree", vim.b.fugitive_type)
    assert.same({ "dir/", "top" }, vim.list_slice(H.lines(0), 3))
    vim.api.nvim_win_set_cursor(0, { 3, 0 })
    H.feed("<CR>")
    assert.same({ "a" }, vim.list_slice(H.lines(0), 3))
    vim.api.nvim_win_set_cursor(0, { 3, 0 })
    H.feed("<CR>")
    assert.same({ "a" }, H.lines(0))
    assert.equals(object.format(repo.root .. "/.git", head, "dir/a"), vim.api.nvim_buf_get_name(0))
  end)

  it("reads commits with their diff, folds per file and navigates", function()
    local repo = H.repo({ files = { ["f"] = "1\n2\n3\n", ["g"] = "g\n" } })
    local parent = repo:rev("HEAD")
    local sha = repo:commit("change both", { ["f"] = "1\nTWO\n3\n", ["g"] = "G\n" })
    vim.cmd("edit " .. vim.fn.fnameescape(object.format(repo.root .. "/.git", sha)))
    assert.equals("git", vim.bo.filetype)
    local lines = H.lines(0)
    assert.equals("tree " .. repo:rev("HEAD^{tree}"), lines[1])
    assert.equals("parent " .. parent, lines[2])
    assert.truthy(H.find_line("^    change both$") or H.find_line("^change both$"))
    local d1 = assert(H.find_line("^diff %-%-git a/f b/f"))
    local d2 = assert(H.find_line("^diff %-%-git a/g b/g"))
    assert.equals("expr", vim.wo.foldmethod)
    assert.equals(1, vim.fn.foldlevel(d1 + 1))
    assert.equals(1, vim.fn.foldlevel(d2 + 1))
    -- ( ) move between items, ]c between hunks
    vim.api.nvim_win_set_cursor(0, { d1, 0 })
    H.feed(")")
    assert.truthy(vim.api.nvim_get_current_line():match("^@@"))
    -- <CR> on a + line opens the new blob at that line
    local plus = assert(H.find_line("^%+TWO"))
    vim.api.nvim_win_set_cursor(0, { plus, 0 })
    H.feed("<CR>")
    assert.equals(object.format(repo.root .. "/.git", sha, "f"), vim.api.nvim_buf_get_name(0))
    assert.equals(2, vim.fn.line("."))
    -- and a - line opens the parent's blob
    vim.cmd("buffer #")
    local minus = assert(H.find_line("^%-2"))
    vim.api.nvim_win_set_cursor(0, { minus, 0 })
    H.feed("<CR>")
    assert.equals(object.format(repo.root .. "/.git", parent, "f"), vim.api.nvim_buf_get_name(0))
    assert.equals(2, vim.fn.line("."))
    -- parent line
    vim.cmd("buffer #")
    vim.api.nvim_win_set_cursor(0, { 2, 0 })
    H.feed("<CR>")
    assert.equals(object.format(repo.root .. "/.git", parent), vim.api.nvim_buf_get_name(0))
  end)

  it("refuses to write", function()
    local repo = H.repo({ files = { ["f"] = "1\n" } })
    vim.cmd("edit " .. vim.fn.fnameescape(object.format(repo.root .. "/.git", "0", "f")))
    assert.has_error(function()
      vim.cmd("write!")
    end)
    assert.equals("nowrite", vim.bo.buftype)
  end)
end)

describe(":Gdiffsplit", function()
  before_each(function()
    H.reset_ui()
  end)

  it("diffs the work tree against the index (index left, focus moves)", function()
    local repo = H.repo({ files = { ["f"] = "1\n2\n" } })
    repo:write("f", "1\nTWO\n")
    vim.cmd("edit " .. repo:path("f"))
    local wt = vim.api.nvim_get_current_win()
    vim.cmd("Gvdiffsplit")
    assert.equals(2, #vim.api.nvim_tabpage_list_wins(0))
    assert.equals(object.format(repo.root .. "/.git", "0", "f"), vim.api.nvim_buf_get_name(0))
    assert.is_true(vim.wo.diff)
    assert.is_true(vim.wo[wt].diff)
    -- index is to the left of the work tree
    assert.is_true(vim.api.nvim_win_get_position(0)[2] < vim.api.nvim_win_get_position(wt)[2])
    -- dq closes it
    H.feed("dq")
    assert.equals(1, #vim.api.nvim_tabpage_list_wins(0))
    assert.is_false(vim.wo.diff)
  end)

  it("diffs against a commit, keeping focus with !", function()
    local repo = H.repo({ files = { ["f"] = "1\n" } })
    local first = repo:rev("HEAD")
    repo:commit("two", { ["f"] = "2\n" })
    vim.cmd("edit " .. repo:path("f"))
    local wt = vim.api.nvim_get_current_win()
    vim.cmd("Gdiffsplit! " .. first)
    assert.equals(wt, vim.api.nvim_get_current_win())
    local other = vim.tbl_filter(function(w)
      return w ~= wt
    end, vim.api.nvim_tabpage_list_wins(0))[1]
    assert.equals(
      object.format(repo.root .. "/.git", first, "f"),
      vim.api.nvim_buf_get_name(vim.api.nvim_win_get_buf(other))
    )
  end)

  it("opens the 3-way conflict layout with d2o/d3o and dp", function()
    local repo = H.repo({ files = { ["c"] = "base\n" } })
    repo:git("checkout", "-q", "-b", "topic")
    repo:commit("topic", { ["c"] = "theirs\n" })
    repo:git("checkout", "-q", "main")
    repo:commit("main", { ["c"] = "ours\n" })
    repo:git("merge", "topic", { allow_fail = true })
    vim.cmd("edit " .. repo:path("c"))
    local wt = vim.api.nvim_get_current_win()
    vim.cmd("Gdiffsplit!")
    local wins = vim.api.nvim_tabpage_list_wins(0)
    assert.equals(3, #wins)
    table.sort(wins, function(a, b)
      return vim.api.nvim_win_get_position(a)[2] < vim.api.nvim_win_get_position(b)[2]
    end)
    assert.equals(
      object.format(repo.root .. "/.git", "2", "c"),
      vim.api.nvim_buf_get_name(vim.api.nvim_win_get_buf(wins[1]))
    )
    assert.equals(wt, wins[2])
    assert.equals(
      object.format(repo.root .. "/.git", "3", "c"),
      vim.api.nvim_buf_get_name(vim.api.nvim_win_get_buf(wins[3]))
    )
    assert.equals(wt, vim.api.nvim_get_current_win())
    assert.truthy(vim.fn.maparg("d2o", "n") ~= "")
    assert.truthy(vim.fn.maparg("d3o", "n") ~= "")
    -- take theirs for the (only) hunk
    vim.cmd("normal! gg")
    H.feed("d3o")
    assert.truthy(vim.iter(H.lines(0)):any(function(l)
      return l == "theirs"
    end))
  end)
end)

describe("conflict markers", function()
  before_each(function()
    H.reset_ui()
  end)

  local function conflicted()
    local mid = "m1\nm2\nm3\nm4\nm5\n"
    local repo = H.repo({ files = { ["c"] = "top\nbase\n" .. mid .. "base2\nend\n" } })
    repo:git("checkout", "-q", "-b", "topic")
    repo:commit("topic", { ["c"] = "top\ntheirs\n" .. mid .. "theirs2\nend\n" })
    repo:git("checkout", "-q", "main")
    repo:commit("main", { ["c"] = "top\nours\n" .. mid .. "ours2\nend\n" })
    repo:git("merge", "topic", { allow_fail = true })
    return repo
  end

  it("jumps between blocks and resolves them", function()
    local repo = conflicted()
    vim.cmd("edit " .. repo:path("c"))
    assert.is_true(vim.b.fugitive_conflict)
    vim.cmd("normal! gg")
    H.feed("]x")
    local first = vim.fn.line(".")
    assert.truthy(vim.api.nvim_get_current_line():match("^<<<<<<<"))
    H.feed("]x")
    assert.is_true(vim.fn.line(".") > first)
    H.feed("[x")
    assert.equals(first, vim.fn.line("."))
    H.feed("ct") -- theirs
    H.feed("]x")
    H.feed("cb") -- both
    assert.same(
      { "top", "theirs", "m1", "m2", "m3", "m4", "m5", "ours2", "theirs2", "end" },
      H.lines(0)
    )
    assert.equals(0, #require("nvim-fugitive.conflict").conflicts(0))
  end)

  it("chooses ours and none, and supports diff3 markers", function()
    local repo = conflicted()
    repo:git("checkout", "--conflict=diff3", "--", "c")
    vim.cmd("edit " .. repo:path("c"))
    vim.cmd("normal! gg")
    H.feed("]x")
    H.feed("co")
    H.feed("]x")
    H.feed("c0")
    assert.same({ "top", "ours", "m1", "m2", "m3", "m4", "m5", "end" }, H.lines(0))
  end)

  it("highlights regions with extmarks and honours g:fugitive_no_maps", function()
    local repo = conflicted()
    vim.g.fugitive_no_maps = 1
    vim.cmd("edit " .. repo:path("c"))
    vim.g.fugitive_no_maps = nil
    local marks =
      vim.api.nvim_buf_get_extmarks(0, vim.api.nvim_get_namespaces().fugitive_conflict, 0, -1, {})
    assert.is_true(#marks > 0)
    assert.equals("", vim.fn.maparg("]x", "n"))
  end)
end)

describe(":Ggrep / :Glgrep", function()
  before_each(function()
    H.reset_ui()
    vim.fn.setqflist({}, "r")
  end)

  it("fills quickfix without telescope and jumps to the first match", function()
    local repo = H.repo({ files = { ["a.txt"] = "foo\nbar\n", ["dir/b.txt"] = "xx foo\n" } })
    vim.cmd("cd " .. repo.root .. "/dir")
    require("nvim-fugitive").setup({ integrations = { telescope = false } })
    vim.cmd("Ggrep foo")
    H.wait(function()
      return #vim.fn.getqflist() == 2
    end, "quickfix")
    local qf = vim.fn.getqflist()
    assert.equals(repo:path("a.txt"), vim.api.nvim_buf_get_name(qf[1].bufnr))
    assert.equals(4, qf[2].col)
    assert.equals(repo:path("a.txt"), vim.api.nvim_buf_get_name(0))
    require("nvim-fugitive").setup({})
  end)

  it(":Glgrep! fills the location list without jumping; tree greps open blobs", function()
    local repo = H.repo({ files = { ["a.txt"] = "old foo\n" } })
    repo:commit("change", { ["a.txt"] = "new\n" })
    vim.cmd("cd " .. repo.root)
    vim.cmd("enew")
    vim.cmd("Glgrep! foo HEAD~1")
    H.wait(function()
      return #vim.fn.getloclist(0) == 1
    end, "loclist")
    local item = vim.fn.getloclist(0)[1]
    assert.equals(
      object.format(repo.root .. "/.git", repo:rev("HEAD~1"), "a.txt"),
      vim.api.nvim_buf_get_name(item.bufnr)
    )
    assert.equals("", vim.api.nvim_buf_get_name(0))
  end)
end)

describe(":GMove / :GRename / :GRemove / :GDelete", function()
  before_each(function()
    H.reset_ui()
  end)

  it("moves relative to the work tree and renames the buffer", function()
    local repo = H.repo({ files = { ["dir/a.txt"] = "a\n" } })
    vim.cmd("cd " .. repo.root)
    vim.cmd("edit " .. repo:path("dir/a.txt"))
    vim.cmd("GMove moved.txt")
    H.wait(function()
      return vim.api.nvim_buf_get_name(0) == repo:path("moved.txt")
    end, "rename")
    assert.equals("R  dir/a.txt -> moved.txt\n", repo:status())
  end)

  it(":GRename is relative to the file's directory", function()
    local repo = H.repo({ files = { ["dir/a.txt"] = "a\n" } })
    vim.cmd("cd " .. repo.root)
    vim.cmd("edit " .. repo:path("dir/a.txt"))
    vim.cmd("GRename b.txt")
    H.wait(function()
      return vim.api.nvim_buf_get_name(0) == repo:path("dir/b.txt")
    end, "rename")
  end)

  it(":GRemove keeps the buffer, :GDelete wipes it", function()
    local repo = H.repo({ files = { ["a"] = "a\n", ["b"] = "b\n" } })
    vim.cmd("cd " .. repo.root)
    vim.cmd("edit " .. repo:path("a"))
    local abuf = vim.api.nvim_get_current_buf()
    vim.cmd("GRemove")
    H.wait(function()
      return repo:status() == "D  a\n"
    end)
    assert.is_true(vim.api.nvim_buf_is_valid(abuf))
    vim.cmd("edit " .. repo:path("b"))
    local bbuf = vim.api.nvim_get_current_buf()
    vim.cmd("GDelete")
    H.wait(function()
      return not vim.api.nvim_buf_is_valid(bbuf) or not vim.api.nvim_buf_is_loaded(bbuf)
    end)
    assert.equals("D  a\nD  b\n", repo:status())
  end)

  it("asks for ! when the file has local modifications", function()
    local repo = H.repo({ files = { ["a"] = "a\n" } })
    repo:write("a", "changed\n")
    repo:git("add", "a")
    repo:write("a", "changed again\n")
    vim.cmd("cd " .. repo.root)
    vim.cmd("edit " .. repo:path("a"))
    local log, restore = H.capture_notify()
    vim.cmd("GRemove")
    H.wait(function()
      return #log > 0
    end)
    restore()
    assert.truthy(log[1].msg:match("add ! to force"))
  end)
end)
