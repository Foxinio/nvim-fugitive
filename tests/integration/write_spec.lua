local H = require("helpers")
local object = require("nvim-fugitive.object")

local function url(repo, commit, path)
  return object.format(repo.root .. "/.git", commit, path)
end

describe("editable index", function()
  local log, restore
  before_each(function()
    H.reset_ui()
    log, restore = H.capture_notify()
  end)
  after_each(function()
    restore()
  end)

  it(":w in an index buffer stages exactly the buffer", function()
    local repo = H.repo({ files = { ["f"] = "1\n2\n" } })
    vim.cmd("cd " .. repo.root)
    vim.cmd("edit " .. vim.fn.fnameescape(url(repo, "0", "f")))
    assert.equals("acwrite", vim.bo.buftype)
    assert.is_true(vim.bo.modifiable)
    vim.api.nvim_buf_set_lines(0, 1, 2, false, { "TWO" })
    vim.cmd("write")
    assert.is_false(vim.bo.modified)
    assert.equals("1\nTWO\n", repo:git("show", ":f"))
    assert.equals("1\n2\n", repo:read("f"))
    assert.equals("MM f\n", repo:status())
  end)

  it("keeps a missing final newline and the file mode", function()
    local repo = H.repo({ files = { ["x.sh"] = "echo" } })
    repo:git("update-index", "--chmod=+x", "x.sh")
    vim.cmd("cd " .. repo.root)
    vim.cmd("edit " .. vim.fn.fnameescape(url(repo, "0", "x.sh")))
    vim.api.nvim_buf_set_lines(0, 0, 1, false, { "echo hi" })
    vim.cmd("write")
    assert.equals("echo hi", repo:git("show", ":x.sh"))
    assert.truthy(repo:git("ls-files", "-s", "x.sh"):match("^100755 "))
  end)

  it("commit and stage buffers stay read-only", function()
    local repo = H.repo({ files = { ["f"] = "1\n" } })
    vim.cmd("edit " .. vim.fn.fnameescape(url(repo, repo:rev("HEAD"), "f")))
    assert.is_false(vim.bo.modifiable)
    assert.equals("nowrite", vim.bo.buftype)
  end)

  it("stages a hunk from :Gdiffsplit with do + :w on the index side", function()
    local content = {}
    for i = 1, 20 do
      content[i] = "l" .. i
    end
    local repo = H.repo({ files = { ["f"] = table.concat(content, "\n") .. "\n" } })
    content[2], content[19] = "TWO", "NINETEEN"
    repo:write("f", table.concat(content, "\n") .. "\n")
    vim.cmd("cd " .. repo.root)
    vim.cmd("edit f")
    vim.cmd("Gdiffsplit") -- focus moves to the index side
    assert.equals(url(repo, "0", "f"), vim.api.nvim_buf_get_name(0))
    vim.api.nvim_win_set_cursor(0, { 2, 0 })
    vim.cmd("diffget")
    vim.cmd("write")
    local staged = repo:git("diff", "--cached")
    assert.truthy(staged:match("%+TWO"))
    assert.falsy(staged:match("NINETEEN"))
  end)
end)

describe(":Gread / :Gwrite / :Gwq", function()
  local log, restore
  before_each(function()
    H.reset_ui()
    log, restore = H.capture_notify()
  end)
  after_each(function()
    restore()
  end)

  local function setup()
    local repo = H.repo({ files = { ["a.txt"] = "committed\n" } })
    repo:write("a.txt", "staged\n")
    repo:git("add", "a.txt")
    repo:write("a.txt", "worktree\nmore\n")
    vim.cmd("cd " .. repo.root)
    return repo
  end

  it(":Gread replaces the buffer with the index version, undoably", function()
    local repo = setup()
    vim.cmd("edit a.txt")
    vim.cmd("Gread")
    assert.same({ "staged" }, H.lines(0))
    assert.is_true(vim.bo.modified)
    assert.equals("worktree\nmore\n", repo:read("a.txt"))
    vim.cmd("silent undo")
    assert.same({ "worktree", "more" }, H.lines(0))
    vim.cmd("1Gread HEAD:a.txt")
    assert.same({ "worktree", "committed", "more" }, H.lines(0))
  end)

  it(":Gwrite in a work-tree file writes and stages it", function()
    local repo = setup()
    vim.cmd("edit a.txt")
    vim.api.nvim_buf_set_lines(0, 0, -1, false, { "final" })
    vim.cmd("Gwrite")
    assert.equals("final\n", repo:read("a.txt"))
    assert.equals("M  a.txt\n", repo:status())
  end)

  it(":Gwrite in a commit blob checks that version out and stages it", function()
    local repo = setup()
    vim.cmd("edit a.txt")
    local wt = vim.api.nvim_get_current_buf()
    vim.cmd("Gedit HEAD:a.txt")
    vim.cmd("Gwrite!")
    assert.equals("committed\n", repo:read("a.txt"))
    assert.equals("", repo:status())
    assert.same({ "committed" }, H.lines(wt))
  end)

  it(":Gwrite :0:path writes only the index", function()
    local repo = setup()
    vim.cmd("enew")
    vim.api.nvim_buf_set_lines(0, 0, -1, false, { "scratch" })
    vim.cmd("Gwrite :0:a.txt")
    assert.equals("scratch\n", repo:git("show", ":a.txt"))
    assert.equals("worktree\nmore\n", repo:read("a.txt"))
  end)

  it("refuses to overwrite a modified buffer without !", function()
    local repo = setup()
    vim.cmd("edit a.txt")
    vim.api.nvim_buf_set_lines(0, 0, -1, false, { "unsaved" })
    vim.cmd("Gsplit HEAD:a.txt")
    vim.cmd("Gwrite")
    assert.equals(vim.log.levels.ERROR, log[#log].level)
    assert.equals("worktree\nmore\n", repo:read("a.txt"))
  end)

  it(":Gwrite in //3 resolves a conflict with theirs; :Gwq closes", function()
    local repo = H.repo({ files = { ["c"] = "base\n" } })
    repo:git("checkout", "-q", "-b", "topic")
    repo:commit("topic", { ["c"] = "theirs\n" })
    repo:git("checkout", "-q", "main")
    repo:commit("main", { ["c"] = "ours\n" })
    repo:git("merge", "topic", { allow_fail = true })
    vim.cmd("cd " .. repo.root)
    vim.cmd("edit c")
    vim.cmd("Gsplit :3:c")
    assert.equals(2, #vim.api.nvim_tabpage_list_wins(0))
    vim.cmd("Gwq")
    assert.equals(1, #vim.api.nvim_tabpage_list_wins(0))
    assert.equals("theirs\n", repo:read("c"))
    assert.equals("M  c\n", repo:status())
  end)
end)
