local H = require("helpers")
local repo_mod = require("fugitive.git.repo")

describe("repo detection", function()
  before_each(function()
    repo_mod._cache = {}
  end)

  it("finds a plain repository from a file and a directory", function()
    local r = H.repo({ files = { ["a/b.txt"] = "x\n" } })
    local repo = assert(repo_mod.find(r:path("a/b.txt")))
    assert.equals(r.root .. "/.git", repo.git_dir)
    assert.equals(r.root .. "/.git", repo.common_dir)
    assert.equals(r.root, repo.worktree)
    assert.equals(repo, repo_mod.find(r:path("a")))
    assert.equals("a/b.txt", repo:rel(r:path("a/b.txt")))
  end)

  it("works for paths that do not exist yet", function()
    local r = H.repo({ files = { ["a"] = "x" } })
    local repo = assert(repo_mod.find(r:path("new/dir/file")))
    assert.equals("new/dir/file", repo:rel(r:path("new/dir/file")))
  end)

  it("resolves linked worktrees to per-worktree and common dirs", function()
    local r = H.repo({ files = { ["f"] = "x" } })
    local wt = H.tmpdir() .. "/wt"
    r:git("worktree", "add", "-q", wt)
    wt = vim.uv.fs_realpath(wt)
    local repo = assert(repo_mod.find(wt .. "/f"))
    assert.equals(r.root .. "/.git", repo.common_dir)
    assert.equals(r.root .. "/.git/worktrees/wt", repo.git_dir)
    assert.equals(wt, repo.worktree)
    assert.equals(repo.git_dir .. "/HEAD", repo:git_path("HEAD"))
    assert.equals(repo.common_dir .. "/refs/heads/main", repo:git_path("refs/heads/main"))
  end)

  it("uses the canonical repo through a symlinked parent directory", function()
    local r = H.repo({ files = { ["f"] = "x" } })
    local link = H.tmpdir() .. "/link"
    vim.uv.fs_symlink(r.root, link)
    local a = assert(repo_mod.find(link .. "/f"))
    local b = assert(repo_mod.find(r:path("f")))
    assert.equals(a, b)
    assert.equals("f", a:rel(link .. "/f"))
  end)

  it("never dereferences the final component of a tracked symlink", function()
    local r = H.repo({ files = { ["target.txt"] = "t", ["dir/inner"] = "i" } })
    vim.uv.fs_symlink("target.txt", r:path("link"))
    vim.uv.fs_symlink("dir", r:path("dirlink"))
    vim.uv.fs_symlink("does-not-exist", r:path("dangling"))
    r:commit("links")
    local repo = assert(repo_mod.find(r:path("link")))
    assert.equals("link", repo:rel(r:path("link")))
    assert.equals("dirlink", repo:rel(r:path("dirlink")))
    assert.equals("dangling", repo:rel(r:path("dangling")))
  end)

  it("keeps a link into another repo in the repo that tracks it", function()
    local a = H.repo({ files = { ["fa"] = "a" } })
    local b = H.repo({ files = { ["fb"] = "b" } })
    vim.uv.fs_symlink(b:path("fb"), a:path("to-b"))
    local repo = assert(repo_mod.find(a:path("to-b")))
    assert.equals(a.root .. "/.git", repo.git_dir)
    assert.equals("to-b", repo:rel(a:path("to-b")))
  end)

  it("resolves files in a submodule to the submodule", function()
    local sub = H.repo({ files = { ["s.txt"] = "s" } })
    local parent = H.repo({ files = { ["p.txt"] = "p" } })
    parent:git("-c", "protocol.file.allow=always", "submodule", "add", "-q", sub.root, "sm")
    parent:commit("add submodule")
    local repo = assert(repo_mod.find(parent:path("sm/s.txt")))
    assert.equals(parent.root .. "/sm", repo.worktree)
    assert.equals(parent.root .. "/.git/modules/sm", repo.git_dir)
    assert.is_true(repo.is_submodule)
    assert.equals("s.txt", repo:rel(parent:path("sm/s.txt")))
  end)

  it("reads config case-insensitively for sections and keys", function()
    local r = H.repo({ files = { ["f"] = "x" } })
    r:git("config", "remote.Origin.URL", "https://example.com/x.git")
    local repo = assert(repo_mod.find(r.root))
    assert.equals("https://example.com/x.git", repo:config("remote.Origin.url"))
    assert.equals("main", (repo:head()))
  end)
end)
